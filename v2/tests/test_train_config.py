"""Tests for train configs and the regenerated Kaggle notebook.

Covers:
  1. configs/train_ball.yaml and train_robot.yaml load correctly via Config.
  2. deploy_imgsz == imgsz invariant for each config (the v1 eval-mismatch bug).
  3. The regenerated frc_train_kaggle.ipynb is valid JSON with the expected cells.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from frcscout.io.config import Config

# ---------------------------------------------------------------------------
# Paths (relative to repo root; tests are run from there via pytest)
# ---------------------------------------------------------------------------

REPO = Path(__file__).parent.parent
BALL_CFG  = REPO / "configs" / "train_ball.yaml"
ROBOT_CFG = REPO / "configs" / "train_robot.yaml"
NOTEBOOK  = REPO / "kaggle" / "frc_train_kaggle.ipynb"


# ---------------------------------------------------------------------------
# 1. Config loading
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("cfg_path", [BALL_CFG, ROBOT_CFG])
def test_config_loads(cfg_path: Path):
    """Config.load() must succeed and return a non-empty dict."""
    assert cfg_path.exists(), f"Config not found: {cfg_path}"
    cfg = Config.load(cfg_path)
    assert isinstance(cfg, dict), f"Config.load returned {type(cfg)}"
    assert len(cfg) > 0, "Config is empty"


@pytest.mark.parametrize("cfg_path", [BALL_CFG, ROBOT_CFG])
def test_required_keys_present(cfg_path: Path):
    """Each train config must define base_model, imgsz, deploy_imgsz, epochs."""
    cfg = Config.load(cfg_path)
    for key in ("base_model", "imgsz", "deploy_imgsz", "epochs"):
        assert cfg.get(key) is not None, (
            f"Missing required key '{key}' in {cfg_path.name}"
        )


# ---------------------------------------------------------------------------
# 2. deploy_imgsz == imgsz invariant
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("cfg_path,label", [
    (BALL_CFG,  "train_ball.yaml"),
    (ROBOT_CFG, "train_robot.yaml"),
])
def test_deploy_imgsz_equals_imgsz(cfg_path: Path, label: str):
    """deploy_imgsz MUST equal imgsz.

    A mismatch inflates eval mAP because the model is evaluated at a different
    resolution than the one it will run at deployment. This was a real v1 bug.
    """
    cfg = Config.load(cfg_path)
    imgsz        = cfg.get("imgsz")
    deploy_imgsz = cfg.get("deploy_imgsz")
    assert imgsz is not None,        f"[{label}] 'imgsz' key missing"
    assert deploy_imgsz is not None, f"[{label}] 'deploy_imgsz' key missing"
    assert int(imgsz) == int(deploy_imgsz), (
        f"[{label}] deploy_imgsz ({deploy_imgsz}) != imgsz ({imgsz}). "
        "Fix the config — these must match."
    )


# ---------------------------------------------------------------------------
# 3. Notebook is valid JSON with expected structure
# ---------------------------------------------------------------------------

def test_notebook_exists():
    """The notebook must exist (regenerated by build_notebook.py)."""
    assert NOTEBOOK.exists(), (
        f"Notebook not found: {NOTEBOOK}. "
        "Run: python kaggle/build_notebook.py"
    )


def test_notebook_is_valid_json():
    """The notebook file must be parseable as valid JSON."""
    text = NOTEBOOK.read_text(encoding="utf-8")
    try:
        nb = json.loads(text)
    except json.JSONDecodeError as e:
        pytest.fail(f"frc_train_kaggle.ipynb is not valid JSON: {e}")
    # Top-level keys required by the nbformat spec.
    assert "cells" in nb,    "Notebook missing 'cells' key"
    assert "nbformat" in nb, "Notebook missing 'nbformat' key"
    assert nb["nbformat"] == 4, f"Expected nbformat 4, got {nb['nbformat']}"


def test_notebook_has_expected_cell_count():
    """The notebook must have at least the baseline number of cells.

    This catches build_notebook.py regressions that accidentally drop cells.
    Expected: >=9 cells (2 markdown + 7 code minimum from the v2 design).
    """
    nb = json.loads(NOTEBOOK.read_text(encoding="utf-8"))
    assert len(nb["cells"]) >= 9, (
        f"Expected >=9 cells, got {len(nb['cells'])}. "
        "A cell may have been accidentally dropped from build_notebook.py."
    )


def test_notebook_has_code_and_markdown_cells():
    """The notebook must have both code and markdown cells."""
    nb = json.loads(NOTEBOOK.read_text(encoding="utf-8"))
    cell_types = {c["cell_type"] for c in nb["cells"]}
    assert "code"     in cell_types, "Notebook has no code cells"
    assert "markdown" in cell_types, "Notebook has no markdown cells"


def test_notebook_setup_cell_checks_gpu():
    """The first code cell must assert torch.cuda.is_available()."""
    nb = json.loads(NOTEBOOK.read_text(encoding="utf-8"))
    code_cells = [c for c in nb["cells"] if c["cell_type"] == "code"]
    assert code_cells, "No code cells found"
    first_code = "".join(code_cells[0]["source"])
    assert "cuda.is_available" in first_code, (
        "First code cell must assert GPU availability "
        "(torch.cuda.is_available())"
    )


def test_notebook_robot_autolabel_uses_bumper_color():
    """The robot autolabel cell must use the bumper_color gate (NOT YOLO-World)."""
    nb = json.loads(NOTEBOOK.read_text(encoding="utf-8"))
    all_code = "\n".join(
        "".join(c["source"])
        for c in nb["cells"] if c["cell_type"] == "code"
    )
    assert "bumper_color" in all_code, (
        "Robot autolabel code must use the bumper_color gate. "
        "YOLO-World produced 0 labels in v1."
    )
    assert "yolov8x-worldv2" not in all_code, (
        "YOLO-World (yolov8x-worldv2) must not appear in the notebook. "
        "It produced 0 robot labels in v1."
    )


def test_notebook_temporal_split_not_random():
    """The split cell must use temporal logic (not random.random())."""
    nb = json.loads(NOTEBOOK.read_text(encoding="utf-8"))
    all_code = "\n".join(
        "".join(c["source"])
        for c in nb["cells"] if c["cell_type"] == "code"
    )
    assert "random.random()" not in all_code, (
        "Notebook must NOT use random.random() for splitting. "
        "Use temporal split (last 15% of each clip's timeline). "
        "Random splits cause val/train near-duplicate leakage -> inflated mAP."
    )
    assert "temporal" in all_code.lower() or "0.85" in all_code, (
        "Notebook split cell must use temporal (85/15) logic."
    )


def test_notebook_exports_both_openvino_and_onnx():
    """Both OpenVINO and ONNX exports must be present."""
    nb = json.loads(NOTEBOOK.read_text(encoding="utf-8"))
    all_code = "\n".join(
        "".join(c["source"])
        for c in nb["cells"] if c["cell_type"] == "code"
    )
    assert "openvino" in all_code, "Notebook must export OpenVINO model"
    assert "onnx"     in all_code, "Notebook must export ONNX fallback"


def test_config_dotted_access():
    """Config.get() with dotted paths must work for aug sub-keys."""
    cfg = Config.load(BALL_CFG)
    # aug is a nested dict
    aug = cfg.get("aug")
    assert isinstance(aug, dict), "aug must be a dict in train_ball.yaml"
    # mosaic must be present
    assert cfg.get("aug.mosaic") is not None, "aug.mosaic missing from train_ball.yaml"
